str1 = 'He likes apples, and she does, too'

print(str1)
print(str1.upper()) # 대문자로! -> str.upper()
print(str1.lower()) # 소문자로.. -> str.lower() 

# swapcase() -> 대소문자 바꿈??!
print(str1.swapcase())

# capitalize() -> 문장의 첫 글자만 대문자로
print(str1.lower().capitalize())

# title() -> 단어의 첫 글자마다 다 대문자
print(str1.lower().title())
