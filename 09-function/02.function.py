def plus(x,y):
    print(f'{x} + {y} = {x+y}')

def minus(x,y):
    print(f'{x} - {y} = {x-y}')

def multiple(x,y):
    print(f'{x} x {y} = {x*y}')

def divide(x,y):
    print(f'{x} / {y} = {x/y}')

plus(4, 16)
minus(15, 5)
multiple(9, 9)

